import heapq

# Representación del grafo mediante Lista de Adyacencia (Diccionario)
grafo = {
    "Lima": {"Trujillo": 550, "Arequipa": 1000, "Cusco": 1100, "Chiclayo": 770},
    "Arequipa": {"Lima": 1000, "Cusco": 500},
    "Cusco": {"Lima": 1100, "Arequipa": 500},
    "Trujillo": {"Lima": 550, "Piura": 450, "Chiclayo": 210},
    "Piura": {"Trujillo": 450, "Chiclayo": 260},
    "Chiclayo": {"Lima": 770, "Trujillo": 210, "Piura": 260}
}

def ruta_menor_costo(grafo, origen, destino):
    # Cola de prioridad: almacena (costo_acumulado, nodo_actual, ruta_recorrida)
    cola = [(0, origen, [])]
    visitados = set()

    while cola:
        costo_actual, nodo_actual, ruta = heapq.heappop(cola)

        if nodo_actual in visitados:
            continue

        visitados.add(nodo_actual)
        ruta = ruta + [nodo_actual]

        if nodo_actual == destino:
            return ruta, costo_actual

        for vecino, costo_tramo in grafo[nodo_actual].items():
            if vecino not in visitados:
                heapq.heappush(cola, (costo_actual + costo_tramo, vecino, ruta))

    return None, float('inf')

# Ejecución de prueba
ruta, costo_total = ruta_menor_costo(grafo, "Lima", "Piura")
